CREATE TABLE niveles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL,
    descripcion VARCHAR(200),
    nombre VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE grados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL,
    nombre VARCHAR(30) NOT NULL,
    nivel_id BIGINT NOT NULL REFERENCES niveles(id)
);
CREATE TABLE cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(15) NOT NULL UNIQUE,
    creditos INTEGER,
    estado VARCHAR(255) NOT NULL,
    grado_id BIGINT NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    tipo VARCHAR(255)
);
CREATE TABLE docentes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido VARCHAR(255) NOT NULL,
    dni VARCHAR(8) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    especialidad VARCHAR(255),
    estado VARCHAR(255) NOT NULL,
    horas_semanales_contratadas INTEGER NOT NULL DEFAULT 30,
    nombre VARCHAR(255) NOT NULL
);
CREATE TABLE aulas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activa BOOLEAN NOT NULL,
    capacidad_maxima INTEGER NOT NULL CHECK (capacidad_maxima >= 1),
    nombre VARCHAR(50) NOT NULL,
    observaciones VARCHAR(200),
    pabellon VARCHAR(50) NOT NULL,
    turno_disponible VARCHAR(10) NOT NULL
);
CREATE TABLE secciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activa BOOLEAN NOT NULL,
    anio_escolar INTEGER NOT NULL,
    capacidad_maxima INTEGER NOT NULL CHECK (capacidad_maxima >= 1),
    docente_tutor_id BIGINT,
    nombre VARCHAR(10) NOT NULL,
    turno VARCHAR(10) NOT NULL,
    grado_id BIGINT NOT NULL REFERENCES grados(id)
);
CREATE TABLE periodos_escolares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_escolar INTEGER NOT NULL,
    creado_por VARCHAR(100), estado VARCHAR(20) NOT NULL,
    fecha_creacion TIMESTAMP, fecha_fin DATE NOT NULL, fecha_inicio DATE NOT NULL,
    fecha_reanudacion DATE, fecha_suspension DATE, motivo_suspension VARCHAR(300),
    nombre VARCHAR(50) NOT NULL
);
CREATE TABLE horarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id BIGINT NOT NULL, dia_semana VARCHAR(255) NOT NULL,
    hora_fin TIME NOT NULL, hora_inicio TIME NOT NULL, seccion_id BIGINT NOT NULL,
    turno VARCHAR(255) NOT NULL,
    curso_id BIGINT NOT NULL REFERENCES cursos(id),
    docente_id BIGINT NOT NULL REFERENCES docentes(id)
);
CREATE TABLE tickets_mantenimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id BIGINT NOT NULL, categoria VARCHAR(50) NOT NULL, descripcion VARCHAR(500) NOT NULL,
    docente_id BIGINT NOT NULL, estado VARCHAR(20) NOT NULL,
    fecha_reporte TIMESTAMP NOT NULL, fecha_resolucion TIMESTAMP,
    notas_resolucion VARCHAR(300), urgencia VARCHAR(20) NOT NULL
);
CREATE INDEX idx_periodo_anio ON periodos_escolares(anio_escolar);
CREATE INDEX idx_periodo_estado ON periodos_escolares(estado);
CREATE INDEX idx_ticket_aula ON tickets_mantenimiento(aula_id);
CREATE INDEX idx_ticket_estado ON tickets_mantenimiento(estado);
