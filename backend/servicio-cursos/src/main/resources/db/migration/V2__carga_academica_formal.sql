CREATE TABLE IF NOT EXISTS asignaciones_academicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id BIGINT NOT NULL REFERENCES cursos(id),
    docente_id BIGINT NOT NULL REFERENCES docentes(id),
    seccion_id BIGINT NOT NULL REFERENCES secciones(id),
    horas_semanales INTEGER NOT NULL CHECK (horas_semanales BETWEEN 1 AND 40),
    anio_escolar INTEGER NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_asignacion_curso_docente_seccion_anio UNIQUE (curso_id, docente_id, seccion_id, anio_escolar)
);
CREATE INDEX IF NOT EXISTS idx_asignacion_seccion ON asignaciones_academicas(seccion_id, anio_escolar);
CREATE INDEX IF NOT EXISTS idx_asignacion_docente ON asignaciones_academicas(docente_id, anio_escolar);
