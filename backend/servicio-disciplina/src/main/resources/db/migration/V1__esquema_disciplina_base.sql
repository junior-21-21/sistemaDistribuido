CREATE TABLE reportes_disciplinarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apoderado_notificado BOOLEAN, descripcion VARCHAR(600) NOT NULL,
    docente_id BIGINT NOT NULL, estado VARCHAR(20) NOT NULL,
    estudiante_id BIGINT NOT NULL, fecha_notificacion TIMESTAMP,
    fecha_reporte TIMESTAMP NOT NULL, observaciones VARCHAR(300),
    seccion_id BIGINT NOT NULL, tipo VARCHAR(30) NOT NULL
);
CREATE INDEX idx_disc_docente ON reportes_disciplinarios(docente_id);
CREATE INDEX idx_disc_estudiante ON reportes_disciplinarios(estudiante_id);
CREATE INDEX idx_disc_fecha ON reportes_disciplinarios(fecha_reporte);
