CREATE SEQUENCE revinfo_seq START WITH 1 INCREMENT BY 50;
CREATE TABLE revinfo (rev INTEGER PRIMARY KEY, revtstmp BIGINT);

CREATE TABLE estudiantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido VARCHAR(255) NOT NULL, dni VARCHAR(8) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE, estado VARCHAR(255) NOT NULL,
    grado_id BIGINT, nombre VARCHAR(255) NOT NULL, seccion_id BIGINT,
    telefono VARCHAR(255)
);
CREATE TABLE estudiantes_aud (
    id BIGINT NOT NULL, rev INTEGER NOT NULL REFERENCES revinfo(rev), revtype SMALLINT,
    apellido VARCHAR(255), dni VARCHAR(8), email VARCHAR(255), estado VARCHAR(255),
    grado_id BIGINT, nombre VARCHAR(255), seccion_id BIGINT, telefono VARCHAR(255),
    PRIMARY KEY (rev, id)
);
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido VARCHAR(255) NOT NULL, debe_cambiar_clave BOOLEAN,
    email VARCHAR(255), estado VARCHAR(255) NOT NULL, nombre VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL, rol VARCHAR(255) NOT NULL,
    ultimo_acceso TIMESTAMP, username VARCHAR(255) NOT NULL UNIQUE,
    estudiante_id BIGINT REFERENCES estudiantes(id)
);
CREATE TABLE apoderados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apellido VARCHAR(255) NOT NULL, dni VARCHAR(8) NOT NULL UNIQUE,
    email VARCHAR(255), nombre VARCHAR(255) NOT NULL, telefono VARCHAR(255)
);
CREATE TABLE apoderados_aud (
    id BIGINT NOT NULL, rev INTEGER NOT NULL REFERENCES revinfo(rev), revtype SMALLINT,
    apellido VARCHAR(255), dni VARCHAR(8), email VARCHAR(255), nombre VARCHAR(255), telefono VARCHAR(255),
    PRIMARY KEY (rev, id)
);
CREATE TABLE apoderado_estudiante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parentesco VARCHAR(255) NOT NULL, permiso_retiro BOOLEAN NOT NULL,
    apoderado_id BIGINT NOT NULL REFERENCES apoderados(id),
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id)
);
CREATE TABLE documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_subida TIMESTAMP NOT NULL, nombre_archivo VARCHAR(255) NOT NULL,
    ruta_local VARCHAR(255) NOT NULL, tipo_documento VARCHAR(255) NOT NULL,
    estudiante_id BIGINT NOT NULL REFERENCES estudiantes(id)
);
CREATE TABLE documentos_aud (
    id BIGINT NOT NULL, rev INTEGER NOT NULL REFERENCES revinfo(rev), revtype SMALLINT,
    fecha_subida TIMESTAMP, nombre_archivo VARCHAR(255), ruta_local VARCHAR(255),
    tipo_documento VARCHAR(255), estudiante_id BIGINT, PRIMARY KEY (rev, id)
);
CREATE TABLE documentos_adjuntos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(50) NOT NULL, datos OID NOT NULL, estudiante_id BIGINT NOT NULL,
    fecha_subida TIMESTAMP NOT NULL, nombre_archivo VARCHAR(100) NOT NULL,
    subido_por VARCHAR(100), tamano_bytes BIGINT NOT NULL, tipo_documento VARCHAR(50) NOT NULL
);
CREATE INDEX idx_doc_estudiante ON documentos_adjuntos(estudiante_id);
CREATE TABLE fichas_medicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alergias VARCHAR(500), condiciones_cronicas VARCHAR(500),
    contacto_emergencia_nombre VARCHAR(100), contacto_emergencia_parentesco VARCHAR(50),
    contacto_emergencia_telefono VARCHAR(15), discapacidades VARCHAR(300),
    estudiante_id BIGINT NOT NULL UNIQUE, fecha_actualizacion TIMESTAMP,
    fecha_creacion TIMESTAMP NOT NULL, medicamentos_habituales VARCHAR(300),
    nro_seguro VARCHAR(50), observaciones_generales VARCHAR(300),
    tipo_sangre VARCHAR(5) NOT NULL, tipo_seguro VARCHAR(20), ultima_actualizacion_por VARCHAR(100)
);
CREATE TABLE atenciones_medicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnostico VARCHAR(800) NOT NULL, fecha_atencion TIMESTAMP NOT NULL,
    motivo VARCHAR(200) NOT NULL, registrado_por VARCHAR(100) NOT NULL,
    tratamiento VARCHAR(800) NOT NULL, ficha_medica_id BIGINT NOT NULL REFERENCES fichas_medicas(id)
);
CREATE INDEX idx_atencion_ficha_fecha ON atenciones_medicas(ficha_medica_id, fecha_atencion);
CREATE TABLE derivaciones_psicologicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(600) NOT NULL, docente_derivador_id BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL, estudiante_id BIGINT NOT NULL,
    fecha_atencion TIMESTAMP, fecha_derivacion TIMESTAMP NOT NULL,
    motivo VARCHAR(50) NOT NULL, notas_psicologo VARCHAR(600), prioridad VARCHAR(20) NOT NULL
);
CREATE INDEX idx_deriv_docente ON derivaciones_psicologicas(docente_derivador_id);
CREATE INDEX idx_deriv_estudiante ON derivaciones_psicologicas(estudiante_id);
