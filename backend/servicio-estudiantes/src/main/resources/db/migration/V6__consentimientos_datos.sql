CREATE TABLE consentimientos_datos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    apoderado_id BIGINT NOT NULL,
    finalidad VARCHAR(40) NOT NULL,
    accion VARCHAR(12) NOT NULL,
    version_politica VARCHAR(30) NOT NULL,
    evidencia VARCHAR(300),
    registrado_por VARCHAR(100) NOT NULL,
    registrado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_consentimiento_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id),
    CONSTRAINT fk_consentimiento_apoderado FOREIGN KEY (apoderado_id) REFERENCES apoderados(id),
    CONSTRAINT ck_consentimiento_accion CHECK (accion IN ('OTORGADO', 'DENEGADO', 'REVOCADO')),
    CONSTRAINT ck_consentimiento_finalidad CHECK (
        finalidad IN ('DATOS_ACADEMICOS', 'SALUD', 'COMUNICACIONES'))
);

CREATE INDEX idx_consentimiento_actual
    ON consentimientos_datos(estudiante_id, finalidad, registrado_en DESC);
