CREATE TABLE notas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bimestre VARCHAR(50) NOT NULL, competencia VARCHAR(100) NOT NULL,
    curso_id BIGINT NOT NULL, docente_id BIGINT NOT NULL,
    escala_literal VARCHAR(2), estudiante_id BIGINT NOT NULL,
    fecha_modificacion TIMESTAMP, fecha_registro TIMESTAMP NOT NULL,
    observaciones VARCHAR(500), periodo_anio VARCHAR(20) NOT NULL,
    seccion_id BIGINT NOT NULL, valor_numerico REAL
);
CREATE INDEX idx_nota_curso ON notas(curso_id);
CREATE INDEX idx_nota_docente ON notas(docente_id);
CREATE INDEX idx_nota_estudiante ON notas(estudiante_id);

CREATE TABLE asistencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id BIGINT NOT NULL, docente_id BIGINT NOT NULL, estado VARCHAR(20) NOT NULL,
    estudiante_id BIGINT NOT NULL, fecha DATE NOT NULL, fecha_modificacion TIMESTAMP,
    fecha_registro TIMESTAMP NOT NULL, horario_id BIGINT NOT NULL,
    justificacion VARCHAR(300), registrado_por VARCHAR(100), seccion_id BIGINT NOT NULL,
    turno VARCHAR(20)
);
CREATE INDEX idx_asistencia_estudiante ON asistencias(estudiante_id);
CREATE INDEX idx_asistencia_fecha ON asistencias(fecha);
CREATE INDEX idx_asistencia_horario ON asistencias(horario_id);
CREATE INDEX idx_asistencia_seccion ON asistencias(seccion_id);
