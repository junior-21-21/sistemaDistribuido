CREATE UNIQUE INDEX IF NOT EXISTS uk_asistencia_estudiante_sesion
    ON asistencias(estudiante_id, horario_id, fecha);

CREATE TABLE IF NOT EXISTS sesiones_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horario_id BIGINT NOT NULL,
    seccion_id BIGINT NOT NULL,
    curso_id BIGINT NOT NULL,
    docente_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    estado VARCHAR(12) NOT NULL DEFAULT 'ABIERTA',
    abierta_por VARCHAR(100), cerrada_por VARCHAR(100),
    fecha_apertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre TIMESTAMP,
    CONSTRAINT uk_sesion_asistencia_horario_fecha UNIQUE (horario_id, fecha)
);
CREATE INDEX IF NOT EXISTS idx_sesion_seccion_fecha ON sesiones_asistencia(seccion_id, fecha);
