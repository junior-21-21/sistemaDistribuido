CREATE TABLE notification_outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, evento_id VARCHAR(150) NOT NULL UNIQUE,
 tipo VARCHAR(50) NOT NULL, estudiante_id BIGINT NOT NULL, asunto VARCHAR(200) NOT NULL,
 mensaje VARCHAR(1000) NOT NULL, estado VARCHAR(20) NOT NULL, intentos INTEGER NOT NULL DEFAULT 0,
 proximo_intento TIMESTAMP NOT NULL, correlation_id VARCHAR(100), creado_en TIMESTAMP NOT NULL,
 enviado_en TIMESTAMP, ultimo_error VARCHAR(1000)
);
CREATE INDEX idx_eval_outbox_pendiente ON notification_outbox(estado,proximo_intento);
