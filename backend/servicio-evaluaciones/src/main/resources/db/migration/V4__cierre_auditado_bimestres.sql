CREATE TABLE bimestres_estado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INTEGER NOT NULL,
    bimestre VARCHAR(20) NOT NULL,
    estado VARCHAR(12) NOT NULL DEFAULT 'ABIERTO',
    actualizado_por VARCHAR(100) NOT NULL,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_bimestre_anio UNIQUE (anio, bimestre),
    CONSTRAINT ck_bimestre_estado CHECK (estado IN ('ABIERTO', 'CERRADO'))
);

CREATE TABLE bimestres_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INTEGER NOT NULL,
    bimestre VARCHAR(20) NOT NULL,
    accion VARCHAR(20) NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    actor VARCHAR(100) NOT NULL,
    ocurrido_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_bimestre_accion CHECK (accion IN ('CIERRE', 'REAPERTURA'))
);

CREATE INDEX idx_bimestre_auditoria_periodo
    ON bimestres_auditoria(anio, bimestre, ocurrido_en DESC);
