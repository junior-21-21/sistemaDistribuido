-- Peso (%) de cada columna de evaluación (competencia o tarea) por sección, área y bimestre.
-- Permite calcular el promedio ponderado del bimestre de cada estudiante.
CREATE TABLE ponderaciones_competencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seccion_id BIGINT NOT NULL,
    curso_id BIGINT NOT NULL,
    bimestre VARCHAR(20) NOT NULL,
    periodo_anio VARCHAR(4) NOT NULL,
    competencia VARCHAR(100) NOT NULL,
    peso NUMERIC(5, 2) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0,
    actualizado_por VARCHAR(100) NOT NULL,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ponderacion_peso CHECK (peso >= 0 AND peso <= 100),
    CONSTRAINT uk_ponderacion_columna UNIQUE (seccion_id, curso_id, bimestre, periodo_anio, competencia)
);

CREATE INDEX idx_ponderacion_contexto
    ON ponderaciones_competencia(seccion_id, curso_id, bimestre, periodo_anio);
