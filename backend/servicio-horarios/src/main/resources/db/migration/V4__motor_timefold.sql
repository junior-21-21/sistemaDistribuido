-- Tablas propias del motor de horarios (Timefold). V1-V3 se conservan solo porque ya
-- están aplicadas en bases existentes; este servicio no usa esas tablas.
CREATE TABLE IF NOT EXISTS room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS timeslot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week SMALLINT CHECK (day_of_week >= 0 AND day_of_week <= 6),
    start_time TIME(6),
    end_time TIME(6)
);

CREATE TABLE IF NOT EXISTS lesson (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject VARCHAR(255),
    teacher VARCHAR(255),
    student_group VARCHAR(255),
    room_id BIGINT REFERENCES room(id),
    timeslot_id BIGINT REFERENCES timeslot(id)
);

CREATE TABLE IF NOT EXISTS parametros_horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    max_clases_por_dia_docente INTEGER NOT NULL
);
