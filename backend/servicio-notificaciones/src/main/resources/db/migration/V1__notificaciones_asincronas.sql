CREATE TABLE notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id VARCHAR(36) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    canal VARCHAR(20) NOT NULL,
    estudiante_id BIGINT NOT NULL,
    asunto VARCHAR(180) NOT NULL,
    mensaje VARCHAR(2000) NOT NULL,
    destinatario VARCHAR(320),
    estado VARCHAR(30) NOT NULL,
    intentos INTEGER NOT NULL DEFAULT 0,
    max_intentos INTEGER NOT NULL DEFAULT 5,
    proximo_intento TIMESTAMP,
    ultimo_error VARCHAR(1000),
    correlation_id VARCHAR(100),
    detalle_proveedor VARCHAR(200),
    creada_en TIMESTAMP NOT NULL,
    actualizada_en TIMESTAMP NOT NULL,
    enviada_en TIMESTAMP,
    CONSTRAINT uk_notificacion_evento_canal UNIQUE (evento_id, canal),
    CONSTRAINT ck_notificacion_canal CHECK (canal IN ('EMAIL','SMS','WHATSAPP')),
    CONSTRAINT ck_notificacion_estado CHECK (estado IN ('PENDIENTE','REINTENTO','ENVIADA','OMITIDA','FALLIDA'))
);
CREATE INDEX idx_notificacion_estado_reintento ON notificaciones(estado, proximo_intento);
CREATE INDEX idx_notificacion_estudiante ON notificaciones(estudiante_id, creada_en DESC);
CREATE INDEX idx_notificacion_correlation ON notificaciones(correlation_id);
